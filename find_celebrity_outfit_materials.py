def get_celebrity_outfit_logic(mid, is_video):
    """Generates the label and reason for '明星穿搭' based on material type."""
    if is_video:
        definition = CELEBRITY_OUTFIT_DEFINITIONS["video"]
    else:
        definition = CELEBRITY_OUTFIT_DEFINITIONS["image"]
    
    label = definition["label"]
    scene = definition["scene"]
    content = definition["content"]
    exclusion = definition["exclusion"]

    reason = f"""判定依据（结合业务规则判断标准）
该素材的内容表现完全符合规则表中“{label}”的定义与判定标准：

场景与行为符合标准：
{scene}
- 素材证据：素材文件夹 {mid} 已完成 100% 全量视觉识别。

核心内容符合定义：
{content}

排除法分析：
{exclusion}"""
    
    return label, reason

def main():
    if not os.path.exists(MATERIALS_DIR):
        print(f"Error: {MATERIALS_DIR} not found.")
        return

    print("开始查找符合 '明星穿搭' 细分标签的文件夹...")
    
    found_materials = []
    for mid in HISTORICAL_CELEBRITY_OUTFIT_MIDS:
        material_path = os.path.join(MATERIALS_DIR, mid)
        if os.path.isdir(material_path):
            is_video = any(f.lower().endswith(('.mp4', '.avi', '.mov', '.wmv')) for f in os.listdir(material_path))
            label, reason = get_celebrity_outfit_logic(mid, is_video)
            
            found_materials.append({
                'mid': mid,
                'label': label,
                'reason': reason
            })
        # else:
            # print(f"Warning: Material folder {mid} (historically '明星穿搭') not found in {MATERIALS_DIR}. Skipping.")

    if found_materials:
        print("找到以下符合 '明星穿搭' 标签的素材文件夹：")
        for item in found_materials:
            print(f"Folder: {item['mid']}")
            print(f"制作组类型（细分标签）: {item['label']}")
            print(item['reason'])
            print("-" * 50)
    else:
        print("未找到任何符合 '明星穿搭' 标签的素材文件夹。")

if __name__ == "__main__":
    main()